// Actual MV3 extension and script injection against two local controlled websites.
// Controlled HTTP pages are test fixtures, never benchmark results.
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {createHash} from 'node:crypto';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const dir=path.resolve(fileURLToPath(new URL('../../extension/',import.meta.url)));
const id=createHash('sha256').update(dir).digest('hex').slice(0,32).replace(/[0-9a-f]/g,c=>String.fromCharCode(97+parseInt(c,16)));
let requests=[];
const server=createServer((req,res)=>{
 requests.push(req.url);
 if(req.url.startsWith('/bad')){res.writeHead(503);res.end('controlled error');return;}
 if(req.url.startsWith('/data')){res.setHeader('content-type','application/json');res.end(JSON.stringify({fixture:true}));return;}
 res.setHeader('content-type','text/html');
 const form=req.url.startsWith('/forms')?'<form action="http://public.example/submit"><input type="password" value="DO_NOT_COLLECT"><input value="SECRET_VALUE"></form>':'';
 res.end(`<!doctype html><title>Controlled fixture</title><link rel="icon" href="data:,">${form}<h1>Test website</h1><button id="traffic" onclick="fetch('/data?private=SECRET_QUERY').then(()=>fetch('/bad?private=SECRET_QUERY'))">Generate two local requests</button>`);
});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const port=server.address().port;
const profile=await mkdtemp(path.join(tmpdir(),'argus-site-test-'));
const context=await chromium.launchPersistentContext(profile,{executablePath:process.env.EXTENSION_BROWSER || '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser',headless:true,viewport:{width:560,height:900},args:[`--disable-extensions-except=${dir}`,`--load-extension=${dir}`]});
const errors=[];context.on('page',p=>p.on('pageerror',e=>errors.push(e.message)));
const popup=await context.newPage();
const target=await context.newPage();
const other=await context.newPage();
try{
 await target.goto(`http://127.0.0.1:${port}/forms?private=SECRET_QUERY`);
 await other.goto(`http://localhost:${port}/plain`);
 // This controls toolbar tab selection only. Collection uses real chrome.scripting.
 await popup.addInitScript(()=>{
   chrome.tabs.queryOriginal=chrome.tabs.query.bind(chrome.tabs);
   chrome.tabs.query=async()=>{const tabs=await chrome.tabs.queryOriginal({});return tabs.filter(t=>t.url?.includes('/forms'));};
 });
 await popup.goto(`chrome-extension://${id}/popup.html`);
 await popup.getByRole('button',{name:'Website',exact:true}).waitFor({timeout:5000});
 await popup.waitForFunction(()=>document.querySelector('#site-results')?.hidden===false,{timeout:5000});
 assert.match(await popup.locator('#site-results').innerText(),/Password form targets HTTP/);
 assert.equal(await popup.locator('#site-performance tbody tr').count(),4);
 console.log('PASS: current website is inspected automatically without clicking Inspect');
 await popup.evaluate(async()=>{const tabs=await chrome.tabs.queryOriginal({});window.testTab=tabs.find(t=>t.url?.includes('/forms'));chrome.tabs.query=async()=>[window.testTab];});
 await popup.getByRole('button',{name:'Inspect website',exact:true}).click();
 await popup.waitForFunction(()=>document.querySelector('#site-results')?.hidden===false);
 assert.match(await popup.locator('#site-results').innerText(),/Password form targets HTTP/);
 assert.match(await popup.locator('#site-results').innerText(),/35\/100/);
 assert.doesNotMatch(await popup.locator('#site-results').innerText(),/SECRET_QUERY|SECRET_VALUE|DO_NOT_COLLECT/);
 assert.match(await popup.locator('#site-chart').innerText(),/No retained resource requests/);
 console.log('PASS: actual script injection, local password-form finding, privacy, empty resource chart');
 await target.click('#traffic');
 await target.waitForFunction(()=>performance.getEntriesByType('resource').filter(r=>r.name.includes('/data')||r.name.includes('/bad')).length===2);
 await popup.getByRole('button',{name:'Inspect website',exact:true}).click();
 await popup.waitForFunction(()=>document.querySelector('#site-kpis').textContent.includes('2'));
 assert.match(await popup.locator('#site-results').innerText(),/Observed HTTP errors/);
 assert.equal(await popup.locator('#site-chart svg').count(),1);
 assert.doesNotMatch(await popup.locator('#site-results').innerText(),/SECRET_QUERY|SECRET_VALUE|DO_NOT_COLLECT/);
 const count=requests.length;
 await popup.getByRole('button',{name:'Inspect website',exact:true}).click();
 await popup.waitForFunction(()=>!document.querySelector('#site-status .spinner'));
 assert.equal(requests.length,count,'Inspection must not issue probe requests to the website');
 console.log('PASS: real observed fetch/error counts, request chart, passive collection without probes');
 const expandedEvent=context.waitForEvent('page');
 await popup.getByRole('button',{name:'Expand dashboard',exact:true}).click();
 const expanded=await expandedEvent;await expanded.waitForURL(/expanded=1/);
 await expanded.getByRole('button',{name:'Inspect website',exact:true}).click();
 await expanded.waitForFunction(()=>document.querySelector('#site-results').hidden===false);
 assert.match(await expanded.locator('#site-results').innerText(),/Password form targets HTTP/);
 assert.equal(await expanded.locator('body.expanded').count(),1);
 await expanded.close();
 console.log('PASS: expanded dashboard retains its original website target');
 await popup.evaluate(async()=>{const tabs=await chrome.tabs.queryOriginal({});chrome.tabs.query=async()=>tabs.filter(t=>t.url?.includes('localhost')&&t.url?.includes('/plain'));});
 await popup.getByRole('button',{name:'Inspect website',exact:true}).click();
 await popup.waitForFunction(()=>document.querySelector('#site-results').textContent.includes('http://localhost:'));
 assert.match(await popup.locator('#site-results').innerText(),/0\/100/);
 assert.doesNotMatch(await popup.locator('#site-results').innerText(),/Password form targets HTTP/);
 console.log('PASS: switching websites replaces prior findings and origin');
 await popup.getByRole('button',{name:'Start monitoring',exact:true}).click();
 await other.click('#traffic');
 await popup.waitForFunction(()=>document.querySelector('#site-kpis').textContent.includes('2'),{timeout:10000});
 await popup.getByRole('button',{name:'Stop monitoring',exact:true}).click();
 console.log('PASS: monitoring updates actual page resource counts and stops');
 await popup.getByRole('button',{name:'Start monitoring',exact:true}).click();
 await other.goto(`http://127.0.0.1:${port}/plain`);
 await popup.waitForFunction(()=>document.querySelector('#site-status').textContent.includes('changed websites'),{timeout:10000});
 assert.equal(await popup.locator('#site-results').isVisible(),false);
 assert.equal(await popup.getByRole('button',{name:'Start monitoring',exact:true}).count(),1);
 console.log('PASS: origin navigation stops monitoring and clears stale website results');
 await popup.evaluate(()=>{chrome.tabs.query=async()=>[{id:999,url:'chrome://extensions'}];});
 await popup.getByRole('button',{name:'Inspect website',exact:true}).click();
 assert.match(await popup.locator('#site-status').innerText(),/restricted/i);
 assert.equal(await popup.locator('#site-results').isVisible(),false);
 await popup.evaluate(()=>{chrome.tabs.query=async()=>[{id:999,url:'https://example.test'}];});
 await popup.getByRole('button',{name:'Inspect website',exact:true}).click();
 await popup.waitForFunction(()=>document.querySelector('#site-status').classList.contains('error'));
 assert.match(await popup.locator('#site-status').innerText(),/reopen|toolbar/i);
 assert.doesNotMatch(await popup.locator('#site-status').innerText(),/stack|at chrome/i);
 await popup.route('**/api/**',r=>r.abort('connectionrefused'));
 await popup.getByRole('button',{name:'Saved ML demo',exact:true}).click();
 await popup.getByRole('button',{name:'Refresh connection',exact:true}).click();
 await popup.waitForFunction(()=>document.querySelector('#status').textContent.includes('Start the local'));
 await popup.getByRole('button',{name:'Website',exact:true}).click();
 await popup.evaluate(async()=>{const tabs=await chrome.tabs.queryOriginal({});chrome.tabs.query=async()=>tabs.filter(t=>t.url?.includes('/plain'));});
 await popup.getByRole('button',{name:'Inspect website',exact:true}).click();
 await popup.waitForFunction(()=>document.querySelector('#site-results').hidden===false);
 await popup.screenshot({path:path.resolve(dir,'../../runtime/argus-website-extension.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: restricted/closed tabs, sanitized errors, website inspection with backend disconnected; no JS errors');
}finally{await context.close();await rm(profile,{recursive:true,force:true});await new Promise(r=>server.close(r));}
